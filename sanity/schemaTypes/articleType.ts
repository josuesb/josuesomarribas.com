import {defineArrayMember, defineField, defineType} from "sanity";

export const articleType = defineType({
  name: "article",
  title: "Article",
  type: "document",
  groups: [
    {name: "content", title: "Content", default: true},
    {name: "media", title: "Media"},
    {name: "seo", title: "SEO"},
    {name: "extras", title: "Extras"},
  ],
  fields: [
    defineField({name: "title", title: "Title", type: "string", group: "content", validation: rule => rule.required()}),
    defineField({name: "slug", title: "Slug", type: "slug", group: "content", options: {source: "title", maxLength: 120}, validation: rule => rule.required()}),
    defineField({
      name: "locale",
      title: "Language",
      type: "string",
      group: "content",
      options: {list: [{title: "English", value: "en"}, {title: "Español", value: "es"}], layout: "radio"},
      validation: rule => rule.required(),
    }),
    defineField({
      name: "translationKey",
      title: "Translation key",
      description: "Shared by the English and Spanish versions.",
      type: "string",
      group: "content",
      validation: rule => rule.required(),
    }),
    defineField({name: "description", title: "Summary", type: "text", rows: 3, group: "content", validation: rule => rule.required().max(320)}),
    defineField({
      name: "body",
      title: "Article body",
      description: "Visual editor. The original HTML remains available as a migration fallback.",
      type: "array",
      group: "content",
      of: [
        defineArrayMember({
          type: "block",
          styles: [
            {title: "Normal", value: "normal"},
            {title: "Heading 1", value: "h1"},
            {title: "Heading 2", value: "h2"},
            {title: "Heading 3", value: "h3"},
            {title: "Heading 4", value: "h4"},
            {title: "Quote", value: "blockquote"},
          ],
          marks: {annotations: [defineArrayMember({name: "link", type: "object", fields: [defineField({name: "href", title: "URL", type: "string", validation: rule => rule.required()})]})]},
        }),
        defineArrayMember({name: "externalImage", title: "Site image", type: "object", fields: [
          defineField({name: "src", title: "Path or URL", type: "string", validation: rule => rule.required()}),
          defineField({name: "alt", title: "Alternative text", type: "string"}),
        ], preview: {select: {title: "alt", subtitle: "src"}}}),
        defineArrayMember({name: "editorialFigure", title: "Editorial figure", type: "object", fields: [
          defineField({name: "src", title: "Path or URL", type: "string", validation: rule => rule.required()}),
          defineField({name: "alt", title: "Alternative text", type: "string"}),
          defineField({name: "caption", title: "Caption", type: "string"}),
        ], preview: {select: {title: "caption", subtitle: "src"}}}),
        defineArrayMember({
          type: "image",
          title: "Managed image",
          options: {hotspot: true},
          fields: [
            defineField({name: "alt", title: "Alternative text", type: "string", validation: rule => rule.required()}),
            defineField({name: "caption", title: "Caption", type: "string"}),
          ],
        }),
        defineArrayMember({name: "codeBlock", title: "Code block", type: "code", options: {withFilename: true}}),
        defineArrayMember({name: "rawHtml", title: "Preserved HTML block", type: "object", fields: [
          defineField({name: "label", title: "Block type", type: "string", readOnly: true}),
          defineField({name: "html", title: "HTML", type: "code", options: {language: "html"}, validation: rule => rule.required()}),
        ], preview: {select: {title: "label"}}}),
      ],
      validation: rule => rule.required().min(1),
    }),
    defineField({
      name: "bodyHtml",
      title: "Original HTML fallback",
      description: "Lossless migration source. Keep until the Portable Text version has passed visual QA.",
      type: "code",
      group: "extras",
      readOnly: true,
      options: {language: "html", languageAlternatives: [{title: "HTML", value: "html"}]},
    }),
    defineField({name: "publicationDate", title: "Publication date", type: "datetime", group: "content", validation: rule => rule.required()}),
    defineField({name: "contentType", title: "Content type", type: "string", group: "content", initialValue: "Blog"}),
    defineField({name: "topic", title: "Topic cluster", type: "reference", to: [{type: "topic"}], group: "content"}),
    defineField({name: "tags", title: "Tags", type: "array", of: [defineArrayMember({type: "string"})], options: {layout: "tags"}, group: "content"}),
    defineField({name: "featured", title: "Featured", type: "boolean", initialValue: false, group: "content"}),
    defineField({name: "mainImage", title: "Managed cover image", type: "image", options: {hotspot: true}, group: "media", fields: [defineField({name: "alt", title: "Alternative text", type: "string"})]}),
    defineField({name: "imagePath", title: "Current image path", description: "Preserved until the asset is uploaded to Sanity.", type: "string", group: "media"}),
    defineField({name: "sourceImagePath", title: "Original image path", type: "string", group: "media"}),
    defineField({name: "imageAlt", title: "Image alternative text", type: "string", group: "media"}),
    defineField({name: "audioPath", title: "Current audio path", type: "string", group: "media"}),
    defineField({name: "audioFile", title: "Managed audio file", type: "file", group: "media", options: {accept: "audio/*"}}),
    defineField({name: "canonical", title: "Canonical override", type: "url", group: "seo"}),
    defineField({name: "legacySlug", title: "Legacy slug", type: "string", group: "seo"}),
    defineField({name: "downloadUrl", title: "Download URL", type: "string", group: "extras"}),
    defineField({name: "downloadText", title: "Download label", type: "string", group: "extras"}),
  ],
  orderings: [{title: "Publication date, newest", name: "publicationDateDesc", by: [{field: "publicationDate", direction: "desc"}]}],
  preview: {
    select: {title: "title", locale: "locale", date: "publicationDate", media: "mainImage"},
    prepare: ({title, locale, date, media}) => ({title, subtitle: `${locale?.toUpperCase() ?? "—"} · ${date ? new Date(date).toLocaleDateString() : "No date"}`, media}),
  },
});
